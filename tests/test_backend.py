def test_whatif_controls_modify_intended_model_inputs(client):
    """
    Verifies that each supported What-If control (walk, carb reduction, sleep)
    directly modifies its intended model input features in the 29-D feature vector.
    """
    # 1. Walk Control Test: must modify steps_sum_30m, activity_intensity, glucose_velocity_15m, glucose
    res_walk = client.post("/api/patients/PT-001/simulate", json={"walk_minutes": 25})
    assert res_walk.status_code == 200
    sim_walk = res_walk.json()
    base_f = sim_walk["baseline_features"]
    sim_f = sim_walk["simulated_features"]
    
    assert sim_f["steps_sum_30m"] > base_f["steps_sum_30m"]
    assert sim_f["steps_sum_30m"] == base_f["steps_sum_30m"] + int(25 * 65.0)
    assert sim_f["activity_intensity"] == 0.65
    assert sim_f["glucose_velocity_15m"] < base_f["glucose_velocity_15m"]
    assert sim_f["glucose"] < base_f["glucose"]
    assert sim_f["glucose_dev_base"] < base_f["glucose_dev_base"]

    # 2. Carbohydrate Reduction Control Test: must modify recent_carbs_60m and glucose_acc_30m
    res_carb = client.post("/api/patients/PT-001/simulate", json={"carb_reduction_percent": 35.0})
    assert res_carb.status_code == 200
    sim_carb = res_carb.json()
    assert sim_carb["simulated_features"]["recent_carbs_60m"] < sim_carb["baseline_features"]["recent_carbs_60m"]
    assert sim_carb["simulated_features"]["glucose_acc_30m"] <= sim_carb["baseline_features"]["glucose_acc_30m"]

    # Also test carb_reduction_pct alias
    res_carb_alias = client.post("/api/patients/PT-001/simulate", json={"carb_reduction_pct": 50.0})
    assert res_carb_alias.status_code == 200
    sim_alias = res_carb_alias.json()
    assert sim_alias["simulated_features"]["recent_carbs_60m"] < sim_alias["baseline_features"]["recent_carbs_60m"]

    # 3. Sleep Control Test: must modify sleep_quality, hrv, hrv_dev_base, hr, hr_dev_base
    res_sleep = client.post("/api/patients/PT-001/simulate", json={"sleep_boost": True, "sleep_bonus_hours": 1.5})
    assert res_sleep.status_code == 200
    sim_sleep = res_sleep.json()
    base_s = sim_sleep["baseline_features"]
    sim_s = sim_sleep["simulated_features"]

    assert sim_s["sleep_quality"] > base_s["sleep_quality"]
    assert sim_s["hrv"] > base_s["hrv"]
    assert sim_s["hrv_dev_base"] > base_s["hrv_dev_base"]
    assert sim_s["hr"] < base_s["hr"]
    assert sim_s["hr_dev_base"] < base_s["hr_dev_base"]

def test_whatif_risk_direction_semantics(client):
    """
    Verifies that What-If simulation accurately classifies and returns risk_direction
    ('DECREASED', 'INCREASED', 'UNCHANGED') and never clamps risk delta to zero.
    """
    # Baseline with no interventions -> UNCHANGED
    res_null = client.post("/api/patients/PT-001/simulate", json={
        "walk_minutes": 0,
        "carb_reduction_percent": 0.0,
        "sleep_boost": False,
        "sleep_bonus_hours": 0.0
    })
    assert res_null.status_code == 200
    sim_null = res_null.json()
    assert sim_null["risk_direction"] == "UNCHANGED"
    assert sim_null["risk_delta"] == 0.0

    # Active beneficial interventions on meal challenge -> DECREASED
    res_active = client.post("/api/patients/PT-001/simulate", json={
        "walk_minutes": 30,
        "carb_reduction_percent": 40.0,
        "sleep_boost": True,
        "sleep_bonus_hours": 2.0
    })
    assert res_active.status_code == 200
    sim_active = res_active.json()
    assert sim_active["risk_direction"] in ["DECREASED", "UNCHANGED"]
    assert sim_active["simulated_risk"] <= sim_active["baseline_risk"]

