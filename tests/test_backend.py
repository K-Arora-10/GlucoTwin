def test_missing_model_artifact_handling(client):
    """
    Verifies that when model artifact is unavailable, the application returns
    clear HTTP 503 Service Unavailable errors instead of silent handwritten fallbacks.
    """
    # Temporarily simulate missing model
    original_model = StateEngine._model
    original_explainer = StateEngine._explainer
    try:
        StateEngine._model = None
        StateEngine._explainer = None
        
        # Health check must report degraded and model_loaded=False
        res_health = client.get("/api/health")
        assert res_health.status_code == 200
        health_data = res_health.json()
        assert health_data["status"] == "degraded"
        assert health_data["model_loaded"] is False
        assert health_data["explainer_loaded"] is False
        
        # Prediction endpoint must return HTTP 503
        res_pred = client.get("/api/patients/PT-001/prediction")
        assert res_pred.status_code == 503
        assert "ModelUnavailableError" in res_pred.json()["detail"]
        
        # Simulation endpoint must return HTTP 503
        res_sim = client.post("/api/patients/PT-001/simulate", json={"walk_minutes": 15})
        assert res_sim.status_code == 503
        assert "ModelUnavailableError" in res_sim.json()["detail"]
        
    finally:
        # Restore original model and explainer
        StateEngine._model = original_model
        StateEngine._explainer = original_explainer
